def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=ROOT / "docs/parity/devices.csv")
    args = parser.parse_args()

    missing: list[str] = []
    for row in ROWS:
        for path in EVIDENCE[row["id"]]:
            if not (ROOT / path).exists():
                missing.append(f"{row['id']}: {path}")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    with args.out.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(ROWS[0].keys()))
        writer.writeheader()
        writer.writerows(ROWS)

    print(f"wrote {len(ROWS)} device/client rows -> {args.out}")
    if missing:
        print("evidence paths not found:", file=sys.stderr)
        for item in missing:
            print("  " + item, file=sys.stderr)
        return 1
    print("all evidence paths resolve")
    return 0


if __name__ == "__main__":
    sys.exit(main())
