import { expect, test } from '@playwright/test'
import { signIn } from './helpers'

test('create, partially ship, post, and reprint a wholesale invoice', async ({ page }) => {
  test.setTimeout(240_000)
  const tag = Date.now().toString(36).slice(-6)
  await page.goto('/sign-in')
  await signIn(page, 'manager')
  await expect(page.getByTestId('nav-menu')).toBeVisible()

  await page.goto('/admin/customers')
  await page.getByTestId('customer-new').click()
  await page.getByTestId('customer-full-name').locator('input').fill(`Wholesale ${tag}`)
  await page.getByTestId('customer-phone').locator('input').fill('604777' + tag.slice(-4))
  await page.getByTestId('customer-email').locator('input').fill(`ws${tag}@example.test`)
  await page.getByTestId('customer-save').click()
  const notice = page.getByTestId('customer-notice')
  await expect(notice).toContainText('Customer')
  const customerId = Number((await notice.innerText()).match(/Customer (\d+) saved/)![1])

  await page.goto('/admin/wholesale')
  await page.getByTestId('wholesale-customer').locator('input').fill(String(customerId))
  await page.getByTestId('wholesale-terms').locator('input').fill('NET30')
  await page.getByTestId('wholesale-term-days').locator('input').fill('30')
  await page.getByTestId('wholesale-credit').locator('input').fill('50000')
  await page.getByTestId('wholesale-tax').locator('input').fill('GST')
  await page.getByTestId('wholesale-save').click()
  await expect(page.getByTestId('wholesale-notice')).toContainText('saved')

  await page.getByTestId('wholesale-price-code').locator('input').fill('A')
  await page.getByTestId('wholesale-price-name').locator('input').fill('E2E wholesale list')
  await page.getByTestId('wholesale-price-items').locator('textarea')
    .fill('30110359,20.0000')
  await page.getByTestId('wholesale-publish').click()
  await expect(page.getByTestId('wholesale-notice')).toContainText('published')

  await page.goto('/admin/wholesale/invoices')
  await expect(page.getByTestId('wholesale-invoice-page')).toBeVisible()
  await page.getByTestId('invoice-customer').locator('input').fill(String(customerId))
  await page.getByTestId('invoice-shipping-method').locator('input').fill('Courier')
  await page.getByTestId('invoice-ship-name').locator('input').fill('Receiving Dock')
  await page.getByTestId('invoice-ship-address').locator('input').fill('10 Wholesale Way')
  await page.getByTestId('invoice-po').locator('input').fill('PO-' + tag)
  await page.getByTestId('invoice-line-sku-0').locator('input').fill('30110359')
  await page.getByTestId('invoice-line-qty-0').locator('input').fill('1')
  await page.getByTestId('invoice-line-price-0').locator('input').fill('20.0000')
  await page.getByTestId('invoice-line-tax-0').locator('input').fill('B')
  await page.getByTestId('invoice-line-backorder-0').locator('input').fill('2')
  await page.getByTestId('invoice-tender-amount-0').locator('input').fill('22.4000')
  await page.getByTestId('invoice-save').click()
  await expect(page.getByTestId('invoice-notice')).toContainText('saved as draft')
  await expect(page.getByTestId('invoice-status')).toContainText('draft')

  await page.getByTestId('invoice-post').click()
  await expect(page.getByTestId('invoice-notice')).toContainText('posted')
  await expect(page.getByTestId('invoice-status')).toContainText('posted')
  await expect(page.getByTestId('invoice-backorders')).toContainText('2')
  await expect(page.getByTestId('invoice-backorders')).toContainText('open')

  await page.getByTestId('invoice-reprint').click()
  await expect(page.getByTestId('invoice-notice')).toContainText('Reprint generated')

  await page.getByTestId('packing-list-open').click()
  await expect(page.getByTestId('packing-list-result')).toContainText('Receiving Dock')
  await expect(page.getByTestId('packing-list-result')).toContainText('backordered 2')
  await expect(page.getByTestId('packing-list-result')).not.toContainText('unit')
  await page.getByTestId('packing-list-reprint').click()
  await expect(page.getByTestId('invoice-notice')).toContainText('Packing-list reprint generated')
})
