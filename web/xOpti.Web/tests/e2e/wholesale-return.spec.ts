import { expect, test } from '@playwright/test'
import { signIn } from './helpers'

test('partial and full wholesale returns with disposition and reprint', async ({ page }) => {
  test.setTimeout(300_000)
  const tag = Date.now().toString(36).slice(-6)
  await page.goto('/sign-in')
  await signIn(page, 'manager')
  await expect(page.getByTestId('nav-menu')).toBeVisible()

  await page.goto('/admin/customers')
  await page.getByTestId('customer-new').click()
  await page.getByTestId('customer-full-name').locator('input').fill(`Return ${tag}`)
  await page.getByTestId('customer-phone').locator('input').fill('604888' + tag.slice(-4))
  await page.getByTestId('customer-email').locator('input').fill(`ret${tag}@example.test`)
  await page.getByTestId('customer-save').click()
  const customerNotice = page.getByTestId('customer-notice')
  await expect(customerNotice).toContainText('Customer')
  const customerId = Number((await customerNotice.innerText()).match(/Customer (\d+) saved/)![1])

  await page.goto('/admin/wholesale')
  await page.getByTestId('wholesale-customer').locator('input').fill(String(customerId))
  await page.getByTestId('wholesale-terms').locator('input').fill('NET30')
  await page.getByTestId('wholesale-term-days').locator('input').fill('30')
  await page.getByTestId('wholesale-credit').locator('input').fill('50000')
  await page.getByTestId('wholesale-tax').locator('input').fill('GST')
  await page.getByTestId('wholesale-save').click()
  await expect(page.getByTestId('wholesale-notice')).toContainText('saved')
  await page.getByTestId('wholesale-price-code').locator('input').fill('A')
  await page.getByTestId('wholesale-price-name').locator('input').fill('Return E2E list')
  await page.getByTestId('wholesale-price-items').locator('textarea')
    .fill('30110359,20.0000')
  await page.getByTestId('wholesale-publish').click()
  await expect(page.getByTestId('wholesale-notice')).toContainText('published')

  await page.goto('/admin/wholesale/invoices')
  await page.getByTestId('invoice-customer').locator('input').fill(String(customerId))
  await page.getByTestId('invoice-line-sku-0').locator('input').fill('30110359')
  await page.getByTestId('invoice-line-qty-0').locator('input').fill('2')
  await page.getByTestId('invoice-line-price-0').locator('input').fill('20.0000')
  await page.getByTestId('invoice-line-tax-0').locator('input').fill('B')
  await page.getByTestId('invoice-tender-amount-0').locator('input').fill('44.8000')
  await page.getByTestId('invoice-save').click()
  await expect(page.getByTestId('invoice-notice')).toContainText('saved as draft')
  await page.getByTestId('invoice-post').click()
  await expect(page.getByTestId('invoice-notice')).toContainText('posted')
  const invoiceNumber = (await page.getByTestId('invoice-notice').innerText())
    .match(/Invoice (WC\d{8}) posted/)![1]

  await page.goto('/admin/wholesale/returns')
  await expect(page.getByTestId('wholesale-return-page')).toBeVisible()
  await page.getByTestId('return-invoice').locator('input').fill(invoiceNumber)
  await page.getByTestId('return-load').click()
  await expect(page.getByTestId('return-returnable')).toContainText('30110359')
  await expect(page.getByTestId('return-returnable')).toContainText('2')
  await page.getByTestId('return-line-qty-0').locator('input').fill('1')
  await page.getByTestId('return-tender-amount-0').locator('input').fill('22.4000')
  await page.getByTestId('return-save').click()
  await expect(page.getByTestId('return-notice')).toContainText('saved as draft')
  await page.getByTestId('return-post').click()
  await expect(page.getByTestId('return-notice')).toContainText('posted')
  await page.getByTestId('return-reprint').click()
  await expect(page.getByTestId('return-notice')).toContainText('Reprint generated')

  await page.getByTestId('return-new').click()
  await page.getByTestId('return-invoice').locator('input').fill(invoiceNumber)
  await page.getByTestId('return-load').click()
  await expect(page.getByTestId('return-returnable')).toContainText('1')
  await page.getByTestId('return-line-qty-0').locator('input').fill('1')
  await page.getByTestId('return-line-restock-0').locator('input').uncheck()
  await page.getByTestId('return-line-reason-0').locator('input').fill('damaged in transit')
  await page.getByTestId('return-tender-amount-0').locator('input').fill('22.4000')
  await page.getByTestId('return-save').click()
  await expect(page.getByTestId('return-notice')).toContainText('saved as draft')
  await page.getByTestId('return-post').click()
  await expect(page.getByTestId('return-notice')).toContainText('posted')
  await expect(page.getByTestId('return-list')).toContainText('WR')

  await page.goto('/admin/wholesale')
  await page.getByTestId('wholesale-customer').locator('input').fill(String(customerId))
  await page.getByTestId('wholesale-balance-load').click()
  await expect(page.getByTestId('wholesale-balance')).toContainText('balance 0.0000')
  await page.getByTestId('wholesale-statement-load').click()
  await expect(page.getByTestId('wholesale-statement')).toContainText('closing 0.0000')
  await expect(page.getByTestId('wholesale-statement')).toContainText('invoiced 44.8000')
  await page.getByTestId('wholesale-statement-print').click()
  await expect(page.getByTestId('wholesale-notice')).toContainText('Statement printed')
})
